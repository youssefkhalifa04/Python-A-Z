"""Les structures conditionnelles en Python.

Ce fichier montre l'utilisation de if, elif et else.
"""

print("--- Structures conditionnelles ---")

note = 14

if note >= 16:
    print("Très bien")
elif note >= 10:
    print("Passable")
else:
    print("Insuffisant")

age = 17
if age >= 18:
    print("Majeur")
else:
    print("Mineur")
