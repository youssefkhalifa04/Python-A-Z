"""Les types des variables en Python.

Ce fichier présente quelques types de base et la fonction type().
"""

print("--- Les types des variables ---")

entier = 42
reel = 3.14
texte = "Python"
vrai_faux = True
rien = None

print("entier =", entier, "| type :", type(entier))
print("reel =", reel, "| type :", type(reel))
print("texte =", texte, "| type :", type(texte))
print("vrai_faux =", vrai_faux, "| type :", type(vrai_faux))
print("rien =", rien, "| type :", type(rien))
