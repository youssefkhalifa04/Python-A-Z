"""Les structures itératives en Python.

Ce fichier montre une boucle for et une boucle while.
"""

print("--- Structures itératives ---")

print("Boucle for :")
for i in range(1, 6):
    print("i =", i)

print("Boucle while :")
compteur = 0
while compteur < 3:
    print("compteur =", compteur)
    compteur += 1
