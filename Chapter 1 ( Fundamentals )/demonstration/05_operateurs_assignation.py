"""Les opérateurs d'assignation en Python.

Ce fichier montre comment modifier une variable avec des raccourcis.
"""

print("--- Opérateurs d'assignation ---")

score = 10
print("score initial =", score)

score += 5
print("après += 5 :", score)

score -= 3
print("après -= 3 :", score)

score *= 2
print("après *= 2 :", score)

score /= 4
print("après /= 4 :", score)

score %= 2
print("après %= 2 :", score)
